//! Font a pixel disegnati a mano per le cifre delle icone della tray (spec §4.1).
//!
//! Due famiglie, ciascuna disegnata per 16, 20, 24, 28 e 32 px:
//! - [`FontKind::Large`]: un solo valore al centro dell'icona ("42", "100", "68°");
//! - [`FontKind::Small`]: due valori impilati nell'icona della rete ("2M" sopra "12M").
//!
//! I glifi sono scritti come ASCII art (`#` acceso, `.` spento) e convertiti in bit
//! durante la compilazione: tutto è `static`, nessuna allocazione e nessun lavoro a runtime.
//!
//! Metriche (cifre larghezza×altezza, tratto verticale/orizzontale in px, spacing):
//!
//! | Icona | Large              | Small                              |
//! |-------|--------------------|------------------------------------|
//! | 16    | 5×10, 2/1, 1       | 4×7, 1/1, 1                        |
//! | 20    | 6×13, 2/2, 1       | 5×9, 2/1, 1                        |
//! | 24    | 8×16, 3/2, 1       | 6×11, 2/1, 1                       |
//! | 28    | 9×18, 3/2, 1       | 6×13, 2/2, 1 (glifi del Large 20)  |
//! | 32    | 10×20, 4/2, 2      | 8×15, 3/2, 1                       |
//!
//! Le cifre hanno tutte la stessa larghezza tranne l'"1", che è stretto: così "100" entra
//! con 1 px di margine per lato e un numero centrato non si sposta quando cambiano le cifre.
//! Nel Large a 16 px due cifre in grassetto (5 + 1 + 5 + 1) lasciano solo 2 px su 14:
//! "1", "°" e "%" sono larghi 2 px, e il "%" è solo un segno condensato (la spec non lo
//! mostra mai nell'icona; da 20 px in su è un "%" vero).
//!
//! Le minuscole `k`, `m`, `g` (rete in bit/s, spec §4.1) servono solo negli Small. Hanno lo stesso
//! numero di righe delle cifre, con il disegno allineato in basso: la `k` ha l'asta a tutta altezza,
//! la `m` e la `g` sono alte come le minuscole (circa 7/10 della cifra), così si distinguono da `K`, `M`,
//! `G` anche a 16 px. Non sono mai più larghe della maiuscola: "12m" e "99k" entrano dove entrano
//! "12M" e "99K". Lo Small a 28 px riusa i glifi del Large a 20 px, che quindi le contiene anch'esso.
//!
//! Posizionamento consigliato (lo fa il chiamante):
//! - Large: `bar = max(2, icon_px / 8)`, `area = icon_px - bar - 2` righe a partire da y = 1;
//!   `y = 1 + (area - height) / 2`, `x = (icon_px - measure) / 2`. Il valore non si sposta
//!   quando la barra compare o sparisce.
//! - Small: `y0 = (icon_px - (2 * height + 1)) / 2`, seconda riga a `y0 + height + 1`;
//!   allineamento a destra con 1 px di margine, così le unità (K, M, G) restano in colonna.

/// Un glifo bitmap. `rows[y]` contiene la riga y; la colonna x (0 = sinistra) è accesa se `(rows[y] >> (width - 1 - x)) & 1 == 1`.
#[derive(Debug)]
pub struct Glyph {
    pub ch: char,
    pub width: u8,
    pub rows: &'static [u16],
}

/// Un font a pixel di altezza fissa.
#[derive(Debug)]
pub struct PixFont {
    pub height: u8,
    pub spacing: u8,
    pub glyphs: &'static [Glyph],
}

/// La famiglia di font: un valore grande al centro o due valori piccoli impilati.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum FontKind {
    Large,
    Small,
}

impl PixFont {
    /// Il glifo per `ch`, se esiste.
    #[must_use]
    pub fn glyph(&self, ch: char) -> Option<&'static Glyph> {
        // Ricerca lineare su 18-21 glifi: più rapida di qualsiasi tabella e senza allocazioni.
        let glyphs: &'static [Glyph] = self.glyphs;
        glyphs.iter().find(|g| g.ch == ch)
    }

    /// Larghezza in pixel di `text`: somma delle larghezze dei glifi + `spacing` tra glifi consecutivi. I caratteri senza glifo sono ignorati. Stringa vuota = 0.
    #[must_use]
    pub fn measure(&self, text: &str) -> u32 {
        let mut total: u32 = 0;
        let mut first = true;
        for g in text.chars().filter_map(|ch| self.glyph(ch)) {
            if !first {
                total = total.saturating_add(u32::from(self.spacing));
            }
            total = total.saturating_add(u32::from(g.width));
            first = false;
        }
        total
    }
}

/// Il font progettato per un'icona di `icon_px` pixel. Taglie progettate: 16, 20, 24, 28, 32. Valori intermedi usano la taglia progettata inferiore; valori < 16 usano 16; valori > 32 usano 32.
#[must_use]
pub fn font_for(icon_px: u32, kind: FontKind) -> &'static PixFont {
    let (large, small): (&'static PixFont, &'static PixFont) = match icon_px {
        0..=19 => (&LARGE_16, &SMALL_16),
        20..=23 => (&LARGE_20, &SMALL_20),
        24..=27 => (&LARGE_24, &SMALL_24),
        28..=31 => (&LARGE_28, &SMALL_28),
        _ => (&LARGE_32, &SMALL_32),
    };
    match kind {
        FontKind::Large => large,
        FontKind::Small => small,
    }
}

// ---------------------------------------------------------------------------
// Conversione dell'ASCII art (solo a tempo di compilazione)
// ---------------------------------------------------------------------------

// Queste funzioni girano solo negli inizializzatori degli static, cioè durante la
// compilazione: un errore diventerebbe un errore di compilazione, mai un panic a runtime.

/// Larghezza di un glifo in ASCII art: la lunghezza comune delle righe.
/// Restituisce 0 se le righe hanno lunghezze diverse, se la larghezza è fuori da 1..=16
/// o se compare un carattere diverso da `#` e `.`: un glifo largo 0 viene segnalato dai test.
#[allow(clippy::cast_possible_truncation)]
const fn art_width(art: &[&str]) -> u8 {
    let [first, ..] = art else { return 0 };
    let width = first.len();
    if width == 0 || width > 16 {
        return 0;
    }
    let mut rest = art;
    while let [row, tail @ ..] = rest {
        if row.len() != width || !only_pixels(row.as_bytes()) {
            return 0;
        }
        rest = tail;
    }
    // width è compreso fra 1 e 16: la conversione non tronca
    // (u8::try_from non è utilizzabile in una const fn).
    width as u8
}

/// Vero se la riga contiene solo `#` e `.`.
const fn only_pixels(mut bytes: &[u8]) -> bool {
    while let [b, tail @ ..] = bytes {
        if *b != b'#' && *b != b'.' {
            return false;
        }
        bytes = tail;
    }
    true
}

/// Una riga di ASCII art in bit: il primo carattere è il bit più significativo.
const fn row_bits(mut bytes: &[u8]) -> u16 {
    let mut bits: u16 = 0;
    while let [b, tail @ ..] = bytes {
        bits = (bits << 1) | (*b == b'#') as u16;
        bytes = tail;
    }
    bits
}

/// Converte le righe di ASCII art di un glifo in bit, una `u16` per riga.
#[allow(clippy::indexing_slicing)]
const fn art_rows<const N: usize>(art: [&str; N]) -> [u16; N] {
    let mut rows = [0u16; N];
    let mut y = 0;
    // y < N: l'indice è sempre valido per entrambi gli array.
    while y < N {
        rows[y] = row_bits(art[y].as_bytes());
        y += 1;
    }
    rows
}

/// Un glifo dalla sua ASCII art, una stringa per riga dall'alto in basso.
macro_rules! glyph {
    ($ch:literal, $($row:literal)+) => {
        Glyph {
            ch: $ch,
            width: art_width(&[$($row),+]),
            rows: &art_rows([$($row),+]),
        }
    };
}

